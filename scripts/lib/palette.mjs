import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
export const HEADER = "generated by scripts/build.mjs from palette/zacess.json, do not edit by hand";
export const REPO = "https://github.com/zacesshq/themes";
export const RAW = "https://raw.githubusercontent.com/zacesshq/themes/main";

export function loadPalette() {
  return JSON.parse(readFileSync(join(ROOT, "palette", "zacess.json"), "utf8"));
}

export function loadSchema() {
  return JSON.parse(readFileSync(join(ROOT, "palette", "schema.json"), "utf8"));
}

